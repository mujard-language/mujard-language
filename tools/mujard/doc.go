package main

// 'mujard doc <out-dir>' writes the language's reference pages: built-ins, object members, boards, keywords
// and units, described libraries, the error catalogue and the per-chip register tables. Everything comes from
// the same tables the compiler uses (NewEditorInfo, the diagnostic catalogue, the .mlib descriptions and
// regs.json), so the docs can never drift from what the compiler accepts.

import (
	"fmt"
	"io"
	"mujard/lang"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func runMujardDoc(args []string, w io.Writer) int {
	out := "mujard-doc"
	for _, a := range args {
		if !strings.HasPrefix(a, "-") {
			out = a
		}
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		fmt.Fprintln(os.Stderr, "doc:", err)
		return 1
	}
	info := lang.NewEditorInfo()
	write := func(name, body string) {
		if err := os.WriteFile(filepath.Join(out, name), []byte(body), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "doc:", err)
		}
	}
	write("builtins.md", docBuiltins(info))
	write("objects.md", docObjects(info))
	write("boards.md", docBoards(info))
	write("keywords-and-units.md", docWords(info))
	write("libraries.md", docLibraries())
	write("errors.md", docErrors())
	write("registers.md", docRegisters(out, write))
	write("capabilities.md", docCapabilities(info))
	write("index.md", docIndex(info))
	fmt.Fprintf(w, "Wrote the reference to %s (index.md is the start page).\n", out)
	return 0
}

// mdEsc keeps table cells from breaking markdown tables.
func mdEsc(s string) string { return strings.ReplaceAll(s, "|", "\\|") }

func docIndex(info *lang.EditorInfo) string {
	var b strings.Builder
	b.WriteString("# Mujard language reference\n\nGenerated by `mujard doc` from the compiler's own tables - it always matches what the compiler accepts.\n\n")
	fmt.Fprintf(&b, "- [Built-ins](builtins.md) - every name the language gives you (%d)\n", len(info.Globals))
	fmt.Fprintf(&b, "- [Objects and their members](objects.md) (%d classes)\n", len(info.Members))
	fmt.Fprintf(&b, "- [Boards and pins](boards.md) (%d boards)\n", len(info.Boards))
	fmt.Fprintf(&b, "- [Keywords and units](keywords-and-units.md)\n")
	b.WriteString("- [Described libraries](libraries.md) - the Arduino libraries `use \"Name\"` type-checks\n")
	b.WriteString("- [Error and warning catalogue](errors.md)\n")
	b.WriteString("- [Chip registers](registers.md) - what `use mujard.regs` knows per chip\n")
	b.WriteString("- [What is proven on each board](capabilities.md) - built, or run on a real board, per capability\n")
	return b.String()
}

// docCapabilities is the plan's honest-claims table: per board, per capability, how far it is proven (lang/capabilities.go).
func docCapabilities(info *lang.EditorInfo) string {
	var b strings.Builder
	b.WriteString("# What is proven on each board\n\n" +
		"**H** ran on a real board and was seen working · **B** a real build of a program using it succeeded · " +
		"**-** generated by the compiler but never built for that board · **L** the language names it but this board has no backend · " +
		"*(blank)* the board doesn't have it. " +
		"Only the build matrix writes B and only a real board run writes H; a program needing something below B gets " +
		"warning W618. `mujard boards caps <board>` shows one board with the evidence.\n\n")
	b.WriteString("| Board |")
	for _, cp := range lang.Capabilities {
		b.WriteString(" " + cp.Name + " |")
	}
	b.WriteString("\n|---|" + strings.Repeat("---|", len(lang.Capabilities)) + "\n")
	mark := map[string]string{lang.LevelHardware: "**H**", lang.LevelBuild: "B", lang.LevelBackend: "-", lang.LevelLanguage: "**L**", lang.LevelNone: ""}
	for _, eb := range info.Boards {
		bd := lang.LookupBoard(eb.Name)
		if bd == nil || bd.Name != eb.Name {
			continue // an upload alias (nano_old) shares its board's row
		}
		fmt.Fprintf(&b, "| %s (`%s`) |", mdEsc(bd.Display), bd.Name)
		for _, cp := range lang.Capabilities {
			b.WriteString(" " + mark[lang.CapabilityLevel(bd, cp.Name)] + " |")
		}
		b.WriteString("\n")
	}
	b.WriteString("\n| Capability | What it is |\n|---|---|\n")
	for _, cp := range lang.Capabilities {
		fmt.Fprintf(&b, "| `%s` | %s |\n", cp.Name, mdEsc(cp.What))
	}
	fmt.Fprintf(&b, "\nNot in Mujard yet (so not in this table): %s.\n", strings.Join(lang.NotInMujardYet, ", "))
	return b.String()
}

func docBuiltins(info *lang.EditorInfo) string {
	var b strings.Builder
	b.WriteString("# Built-ins\n\nEvery name a program can use. `[lib]` names need `use mujard.<name>` first; `[test]` names only work inside `test` blocks.\n\n")
	b.WriteString("| Name | Kind | Signature |\n|---|---|---|\n")
	for _, g := range info.Globals {
		tags := ""
		if g.Lib != "" {
			tags += " `use mujard." + g.Lib + "`"
		}
		if g.Test {
			tags += " `[test]`"
		}
		fmt.Fprintf(&b, "| `%s` | %s%s | `%s` |\n", g.Name, g.Kind, tags, mdEsc(g.Detail))
	}
	return b.String()
}

func docObjects(info *lang.EditorInfo) string {
	var b strings.Builder
	b.WriteString("# Objects and their members\n\n")
	var names []string
	for c := range info.Members {
		names = append(names, c)
	}
	sort.Strings(names)
	for _, c := range names {
		fmt.Fprintf(&b, "## `%s`\n\n| Member | Kind | Signature |\n|---|---|---|\n", c)
		for _, m := range info.Members[c] {
			fmt.Fprintf(&b, "| `%s` | %s | `%s` |\n", m.Name, m.Kind, mdEsc(m.Detail))
		}
		b.WriteString("\n")
	}
	return b.String()
}

func docBoards(info *lang.EditorInfo) string {
	var b strings.Builder
	b.WriteString("# Boards and pins\n\n`board <name>` picks the target. The pin names are what a program writes (`pin 13`, `pin A0`, `pin LED_BUILTIN`).\n\n")
	for _, bd := range info.Boards {
		fmt.Fprintf(&b, "## `%s` - %s\n\n", bd.Name, bd.Display)
		if len(bd.Pins) > 0 {
			var names []string
			for n := range bd.Pins {
				names = append(names, n)
			}
			sort.Strings(names)
			var parts []string
			for _, n := range names {
				parts = append(parts, fmt.Sprintf("`%s`=%d", n, bd.Pins[n]))
			}
			b.WriteString("Pin names: " + strings.Join(parts, " ") + "\n\n")
		}
		fmt.Fprintf(&b, "- Pins: %s\n- PWM: %s\n- Analog: %s\n\n", ints(bd.Valid), ints(bd.PWM), ints(bd.Analog))
	}
	return b.String()
}

func ints(ns []int) string {
	if len(ns) == 0 {
		return "-"
	}
	s := make([]int, len(ns))
	copy(s, ns)
	sort.Ints(s)
	var parts []string
	for _, n := range s {
		parts = append(parts, fmt.Sprint(n))
	}
	return strings.Join(parts, ", ")
}

func docWords(info *lang.EditorInfo) string {
	var b strings.Builder
	b.WriteString("# Keywords and units\n\n## Keywords\n\n")
	b.WriteString("`" + strings.Join(info.Keywords, "` `") + "`\n\n## Statement words\n\n")
	b.WriteString("`" + strings.Join(info.Statements, "` `") + "`\n\n## Units\n\n")
	b.WriteString("`" + strings.Join(info.Units, "` `") + "`\n")
	return b.String()
}

func docLibraries() string {
	var b strings.Builder
	b.WriteString("# Described libraries\n\n`use \"Name\"` (or `use arduino \"Name\"`) brings a library in; the checker verifies its calls against the shipped description. `use mujard.<name>` libraries are built in and listed under Built-ins.\n\n")
	libs := lang.DescribedLibs()
	sort.Slice(libs, func(i, j int) bool { return libs[i].Name < libs[j].Name })
	for _, d := range libs {
		fmt.Fprintf(&b, "## `%s`\n\n- include: `%s`\n", d.Name, d.Header)
		if len(d.Architectures) > 0 {
			fmt.Fprintf(&b, "- architectures: %s\n", strings.Join(d.Architectures, ", "))
		}
		if len(d.Takes) > 0 {
			fmt.Fprintf(&b, "- takes over: %s\n", strings.Join(d.Takes, ", "))
		}
		b.WriteString("\n")
		var classes []string
		for c := range d.Classes {
			classes = append(classes, c)
		}
		sort.Strings(classes)
		for _, c := range classes {
			cl := d.Classes[c]
			fmt.Fprintf(&b, "### `%s`\n\n", c)
			if fam := d.Families[c]; fam != nil {
				docFamily(&b, c, fam)
			} else if cl.Abstract {
				b.WriteString("- a base class: make one of the classes that extend it\n")
			}
			if cl.Extends != "" {
				fmt.Fprintf(&b, "- extends `%s` (everything it has, this has too)\n", cl.Extends)
			}
			for i := range cl.Ctors {
				fmt.Fprintf(&b, "- new: `%s`\n", mdEsc(libSig(c, &cl.Ctors[i])))
			}
			var ms []string
			for m := range cl.Methods {
				ms = append(ms, m)
			}
			sort.Strings(ms)
			for _, m := range ms {
				fmt.Fprintf(&b, "- `%s`\n", mdEsc(libSig(m, cl.Methods[m])))
			}
			var fs []string
			for f, t := range cl.Fields {
				fs = append(fs, f+": "+t)
			}
			sort.Strings(fs)
			for _, f := range fs {
				fmt.Fprintf(&b, "- `%s`\n", f)
			}
			b.WriteString("\n")
		}
		if len(d.Functions) > 0 {
			var fs []string
			for f := range d.Functions {
				fs = append(fs, f)
			}
			sort.Strings(fs)
			for _, f := range fs {
				fmt.Fprintf(&b, "- `%s`\n", mdEsc(libSig(f, d.Functions[f])))
			}
			b.WriteString("\n")
		}
	}
	return b.String()
}

// docFamily lists a class family by its bus variants - one constructor each, and how many displays come in it -
// rather than the thousands of class names (the checker knows every one).
func docFamily(b *strings.Builder, base string, fam *lang.LibFamily) {
	mids := "<buffer>"
	if len(fam.Mids) > 0 {
		mids = strings.Join(fam.Mids, "|")
	}
	fmt.Fprintf(b, "- the classes `%s<display>_%s_<bus>` all extend `%s`; a misspelt display is an unknown name\n", fam.Prefix, mids, base)
	var vs []string
	for v := range fam.Variants {
		vs = append(vs, v)
	}
	sort.Strings(vs)
	for _, v := range vs {
		va := fam.Variants[v]
		example := ""
		if len(va.Stems) > 0 {
			example = fmt.Sprintf(", e.g. `%s%s_%s_%s`", fam.Prefix, va.Stems[0], firstOr(fam.Mids, ""), v)
		}
		fmt.Fprintf(b, "- bus `%s` (%d displays%s): `%s`\n", v, len(va.Stems), example, mdEsc(libSig("new", &va.Ctor)))
	}
}

func firstOr(s []string, def string) string {
	if len(s) == 0 {
		return def
	}
	return s[0]
}

func libSig(name string, f *lang.LibFn) string {
	var ps []string
	for _, p := range f.Params {
		s := p.Name
		if p.Type != "" {
			s += ": " + p.Type
		}
		if p.Optional {
			s += "?"
		}
		ps = append(ps, s)
	}
	r := name + "(" + strings.Join(ps, ", ") + ")"
	if f.Result != "" && f.Result != "void" {
		r += " -> " + f.Result
	}
	return r
}

var diagGroups = []struct {
	prefix, title string
}{
	{"L", "Lexer (L1xx)"}, {"P", "Parser (P2xx)"}, {"C", "Compile (C3xx)"},
	{"B", "Board and pins (B4xx)"}, {"U", "Units (U5xx)"}, {"W", "Warnings (W6xx)"},
	{"E", "Other"},
}

func docErrors() string {
	var b strings.Builder
	b.WriteString("# Error and warning catalogue\n\nEvery diagnostic the compiler can report, from its message table.\n\n")
	cat := lang.Catalogue()
	var codes []string
	for c := range cat {
		codes = append(codes, c)
	}
	sort.Strings(codes)
	for _, g := range diagGroups {
		var list []string
		for _, c := range codes {
			if strings.HasPrefix(c, g.prefix) {
				list = append(list, c)
			}
		}
		if len(list) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n| Code | Message |\n|---|---|\n", g.title)
		for _, c := range list {
			fmt.Fprintf(&b, "| %s | %s |\n", c, mdEsc(cat[c]))
		}
		b.WriteString("\n")
	}
	return b.String()
}

// docRegisters writes registers.md plus one regs-<chip>.md per chip and returns the index page's body.
func docRegisters(out string, write func(string, string)) string {
	var b strings.Builder
	b.WriteString("# Chip registers\n\n`use mujard.regs` gives `regs.<NAME>`: `.read()`, `.write(v)`, `.set(bits)`, `.clear(bits)`, and `.<FIELD>` names a bit-field's mask. Register names are `PERIPHERAL_REGISTER` on SVD chips and the io-header names on AVR. The tables below are generated from the chip makers' description files.\n\n")
	var chips []string
	for c := range lang.ChipRegs() {
		chips = append(chips, c)
	}
	sort.Strings(chips)
	b.WriteString("| Chip | Registers | Page |\n|---|---|---|\n")
	for _, c := range chips {
		t := lang.ChipRegs()[c]
		page := "regs-" + c + ".md"
		fmt.Fprintf(&b, "| `%s` | %d | [regs-%s.md](%s) |\n", c, len(t), c, page)
		write(page, docChipRegs(c, t))
	}
	return b.String()
}

func docChipRegs(chip string, t map[string]lang.RegDef) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# Registers - %s\n\n| Name | Address | Bits | Fields | Drives pins |\n|---|---|---|---|---|\n", chip)
	var names []string
	for n := range t {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		r := t[n]
		var fs []string
		for f, m := range r.Fields {
			fs = append(fs, fmt.Sprintf("%s=0x%X", f, m))
		}
		sort.Strings(fs)
		fields := strings.Join(fs, " ")
		if len(fields) > 240 {
			fields = fields[:240] + "..."
		}
		fmt.Fprintf(&b, "| `%s` | 0x%X | %d | %s | %s |\n", n, r.Addr, r.Bits, fields, ints(r.Port))
	}
	return b.String()
}
